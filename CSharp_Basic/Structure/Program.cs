namespace Structure // Namespace
{
    class Program // ชื่อคลาส (ชื่อไฟล์)
    {
        static void Main(string[] args) // เมธอด main (เมธอดพิเศษใช้สำหรับรันโปรแกรม)
        {
            // 1. ขอบเขต (Block) ใช้ { } บอกจุดเริ่มต้นและสิ้นสุดของกลุ่มคำสั่ง
            Console.WriteLine("Hello, World!");

            // 2. เครื่องหมายสิ้นสุดคำสั่ง ใช้ ;
            Console.WriteLine("Hello");
            Console.WriteLine("World");

            // 3. Comment บรรทัดเดียว
            /*
             แบบหลายบรรทัด
             บรรทัดที่ 1
             */
        }
    }
}
